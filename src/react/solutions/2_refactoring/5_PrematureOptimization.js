import React, { useState } from 'react';

export default function SimpleCalculator({ a = 2, b = 3 }) {
  const [value, setValue] = useState('');

  //  ПРАВИЛЬНО: Дешевые операции вычисляем напрямую при рендере
  const sum = a + b; 

  //  ПРАВИЛЬНО: Обычная функция, сборщик мусора (Garbage Collector) в JS 
  // легко с ней справится, это не вызовет проблем с производительностью
  const handleChange = (e) => { 
    setValue(e.target.value);
  };

  return (
    <div>
      <p>Сумма: {sum}</p>
      <input type="text" value={value} onChange={handleChange} />
    </div>
  );
}

/*
=== Разбор решения ===

1. useMemo для сложения двух чисел — это выстрел в ногу. Сложение выполняется за доли наносекунды. А вот вызов useMemo, создание массива зависимостей [a, b] и их сравнение при каждом рендере занимают куда больше времени работы движка JS.

2. useCallback имеет смысл, только если функция передается в дочерний компонент, обернутый в React.memo (или используется в зависимостях других хуков вроде useEffect). Тег <input> — это встроенный DOM-узел, React не кэширует его рендеры на основе ссылок на функции. Этот useCallback просто ест память.

Как надо (Рефакторинг): Удаляем лишние хуки и пишем чистый, легковесный код.
*/
