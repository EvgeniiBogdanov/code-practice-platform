import React from 'react';

/**
 * Собеседование: React + TypeScript
 * 
 * КОНТЕКСТ:
 * В проекте разрабатывается переиспользуемый компонент списка `List` для отображения
 * коллекций любых сущностей (пользователи, товары, комментарии).
 *
 * ПРОБЛЕМА:
 * Текущая реализация использует тип `any`, из-за чего теряется типобезопасность:
 * в функции рендера свойства элементов не проверяются компилятором, а использование
 * индекса массива в качестве `key` приводит к ошибкам синхронизации при сортировке или фильтрации.
 *
 * ТРЕБОВАНИЯ:
 * 1. Реализуйте компонент так, чтобы он автоматически сохранял и выводил точный тип элементов
 *    переданного массива `items` без необходимости ручного приведения типов при использовании.
 * 2. Добавьте обязательный механизм извлечения уникального ключа для каждого элемента.
 * 3. Функция рендеринга должна принимать строго типизированный элемент и возвращать валидный
 *    для React контент.
 */

type ListProps = {
  items: any[];
  renderItem: (item: any) => React.ReactNode;
};

export function List(props: ListProps) {
  return (
    <ul>
      {props.items.map((item, index) => (
        <li key={index}>{props.renderItem(item)}</li>
      ))}
    </ul>
  );
}

// Пример использования:
export default function Demo() {
  const users = [
    { id: 1, name: 'Алексей' },
    { id: 2, name: 'Мария' }
  ];

  return (
    <List 
      items={users} 
      renderItem={(user) => <span>{user.name}</span>} 
    />
  );
}
