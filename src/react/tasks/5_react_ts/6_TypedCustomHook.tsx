import React, { useState } from 'react';

/**
 * Собеседование: React + TypeScript
 * 
 * КОНТЕКСТ:
 * Разработан кастомный хук `useToggle`, возвращающий флаг состояния и функцию его переключения
 * по аналогии с кортежем, возвращаемым хуком `useState`.
 *
 * ПРОБЛЕМА:
 * TypeScript выводит возвращаемое значение хука как обычный массив объединенных типов `(boolean | Function)[]`.
 * Из-за этого при деструктуризации переменная `isOn` не определяется строго как `boolean`, и компилятор
 * выдает ошибку при попытке использовать её в условиях или передать в качестве булевого пропа.
 *
 * ТРЕБОВАНИЯ:
 * 1. Типизируйте возвращаемое значение хука так, чтобы компилятор строго определял его как кортеж фиксированной структуры:
 *    первый элемент — `boolean`, второй элемент — функция переключения.
 * 2. Убедитесь, что полученные при деструктуризации переменные корректно используются в JSX без ошибок компиляции.
 */

export function useToggle(initialValue = false) {
  const [value, setValue] = useState(initialValue);
  const toggle = () => setValue((prev) => !prev);

  return [value, toggle];
}

export default function Demo() {
  const [isOn, toggle] = useToggle(false);

  return (
    <div>
      <p>Состояние: {isOn ? 'Включено' : 'Выключено'}</p>
      <button onClick={toggle}>Переключить</button>
    </div>
  );
}
