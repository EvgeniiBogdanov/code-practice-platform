// Функция createElement должна возвращать разный тип объекта
// в зависимости от переданной строки тега:
// "img" -> объект с полем src,
// "a" -> объект с полем href,
// любой другой тег -> объект без дополнительных полей.
//
// Тип результата должен определяться уже на этапе вызова функции,
// а не через объединение всех возможных вариантов.

function createElement(tag) {
  if (tag === "img") {
    return { tag, src: "" };
  }
  if (tag === "a") {
    return { tag, href: "" };
  }
  return { tag };
}
