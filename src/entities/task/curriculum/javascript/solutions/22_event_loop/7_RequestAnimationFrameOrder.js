console.log("A"); // 1. Синхронно -> "A"

setTimeout(() => {
  console.log("B"); // Макрозадача (таймер)
}, 0);

requestAnimationFrame(() => {
  console.log("C"); // Колбэк фазы перерисовки (Rendering Pipeline)
});

Promise.resolve().then(() => {
  console.log("D"); // 2. Микрозадача -> "D"
});

console.log("E"); // 1. Синхронно -> "E"

// Порядок вывода:
// 1. Синхронный код: A, E
// 2. Очередь микрозадач: D
// 3. Очередь макрозадач / Rendering:
//    - Порядок вывода B (setTimeout) и C (rAF) НЕ детерминирован спецификацией:
//      Если шаг перерисовки браузера происходит до следующей макрозадачи: A, E, D, C, B
//      Если макрозадача таймера выполняется до шага перерисовки: A, E, D, B, C
