// Плеер шлёт метрики просмотра: старт, паузы, буферизацию, смену качества, ошибки. Отдельный
// запрос на каждое событие конкурирует с видео за сеть, а один отчёт в конце теряется, если
// зритель закрыл вкладку. Нужна очередь, которая отправляет события пачками.
//
// Реализуйте createEventBatcher({ send, maxBatch, flushMs, maxQueue }):
// - track(event) кладёт событие в очередь;
// - как только в очереди maxBatch событий, первые maxBatch уходят одной пачкой через send(batch);
// - неполная пачка уходит через flushMs после того, как в пустую очередь попало первое событие;
//   когда очередь опустела после отправки, отсчёт начинается заново со следующего события;
// - одновременно идёт не больше одного send: события, пришедшие во время отправки, ждут её конца;
// - отклонённая пачка возвращается в начало очереди и уходит со следующей отправкой,
//   порядок событий сохраняется;
// - очередь не растёт бесконечно: сверх maxQueue выбрасываются самые старые события;
// - flush() сразу отправляет всё накопленное пачками не больше maxBatch (уход со страницы)
//   и завершается, когда отправлять нечего или отправка не удалась.

export interface EventBatcherOptions<E> {
  send: (batch: E[]) => Promise<void>;
  maxBatch: number;
  flushMs: number;
  maxQueue: number;
}

export interface EventBatcher<E> {
  track: (event: E) => void;
  flush: () => Promise<void>;
}

export function createEventBatcher<E>({
  send,
  maxBatch,
  flushMs,
  maxQueue,
}: EventBatcherOptions<E>): EventBatcher<E> {
  // Каждое событие — отдельный запрос.
  return {
    track: (event) => {
      send([event]).catch(() => {});
    },
    flush: async () => {},
  };
}
