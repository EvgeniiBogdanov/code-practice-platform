// Обработчик скролла вызывает загрузку сотни раз в секунду. Нам нужно выполнять
// функцию не чаще одного раза в интервал, но не потерять финальное состояние:
// последнее положение скролла должно обработаться.
//
// Реализуйте createThrottle(fn, intervalMs):
// - первый вызов call(...args) выполняется сразу и открывает окно длиной intervalMs;
// - вызовы внутри окна не выполняются, запоминается только последний набор аргументов;
// - по окончании окна, если были вызовы, fn выполняется с последними аргументами
//   и открывается новое окно;
// - если внутри окна вызовов не было, следующий call снова выполняется сразу;
// - cancel() отменяет ожидающий завершающий вызов и сбрасывает окно.

export interface Throttled<A extends unknown[]> {
  call: (...args: A) => void;
  cancel: () => void;
}

export function createThrottle<A extends unknown[]>(
  fn: (...args: A) => void,
  intervalMs: number
): Throttled<A> {
  return {
    call: () => {},
    cancel: () => {},
  };
}
