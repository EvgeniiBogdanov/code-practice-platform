// В таблице формулы ссылаются на ячейки, а те — на другие формулы. После изменения ячейки
// нужно пересчитать только то, что от неё зависит, каждую формулу один раз и в правильном
// порядке: формула считается после всех ячеек, которые она читает. Цикл (A1 = B1 + 1,
// B1 = A1 + 1) должен стать ошибкой, а не зависанием вкладки.
//
// Реализуйте createSheet():
// - setValue(id, number) записывает число (и убирает прежнюю формулу ячейки);
// - setFormula(id, deps, compute) записывает формулу: deps — адреса ячеек, compute получает
//   их значения в том же порядке и возвращает число; формула сразу считается;
//   прежняя формула ячейки заменяется вместе со своими зависимостями;
// - пустая ячейка в deps даёт 0;
// - оба метода возвращают список пересчитанных формул в порядке пересчёта: изменённую
//   формулу и все формулы, которые зависят от изменённой ячейки напрямую или через другие;
// - каждая формула считается один раз и только после всех своих зависимостей из этого списка;
//   формулы, которые от изменения не зависят, не пересчитываются;
// - ячейки цикла и всё, что от них зависит, получают значение "#CYCLE" и не попадают
//   в список; формула, которая читает ячейку со значением "#CYCLE", тоже даёт "#CYCLE";
// - get(id) возвращает значение ячейки или undefined.

export type CellValue = number | "#CYCLE";

export interface Sheet {
  setValue: (id: string, value: number) => string[];
  setFormula: (
    id: string,
    deps: readonly string[],
    compute: (values: number[]) => number
  ) => string[];
  get: (id: string) => CellValue | undefined;
}

export function createSheet(): Sheet {
  // Формула считается один раз при записи и больше не обновляется.
  const values = new Map<string, CellValue>();
  return {
    setValue: (id, value) => {
      values.set(id, value);
      return [];
    },
    setFormula: (id, deps, compute) => {
      values.set(id, compute(deps.map((dep) => Number(values.get(dep) ?? 0))));
      return [id];
    },
    get: (id) => values.get(id),
  };
}
