useEffect(() => {
  // 1. Синхронизация с внешней системой: подписка, таймер, запрос, DOM API
  const id = setInterval(tick, 1000);

  // 2. Cleanup: React вызывает его перед следующим запуском эффекта и при размонтировании
  return () => clearInterval(id);
}, [tick]); // 3. Зависимости: эффект перезапускается, когда tick меняется по Object.is

// Варианты массива зависимостей:
// useEffect(fn)        — после каждого рендера
// useEffect(fn, [])    — один раз после монтирования
// useEffect(fn, [a, b]) — после монтирования и при изменении a или b
