import type { SectionType } from "@/entities/task/meta";
import type { SkillDefinition, SkillTaskEntry } from "../types";
import { ALGORITHM_SKILLS } from "./algorithmSkills";
import { JAVASCRIPT_SKILLS } from "./javascriptSkills";
import { REACT_SKILLS } from "./reactSkills";
import { TYPESCRIPT_SKILLS } from "./typescriptSkills";
import skillTaskIndex from "./skillTaskIndex.json";

/** Catalog order is the intended learning path: JavaScript → TypeScript → React → algorithms. */
export const SKILLS: readonly SkillDefinition[] = [
  ...JAVASCRIPT_SKILLS,
  ...TYPESCRIPT_SKILLS,
  ...REACT_SKILLS,
  ...ALGORITHM_SKILLS,
];

export const SKILL_SECTIONS: readonly SectionType[] = [
  "javascript",
  "typescript",
  "react",
  "algorithms",
];

/** Generated by `npm run generate:skill-index`; ordered by skill, then step, then route order. */
export const SKILL_TASK_INDEX: readonly SkillTaskEntry[] = skillTaskIndex;

const skillById = new Map(SKILLS.map((skill) => [skill.id, skill]));
const entryByTaskId = new Map(SKILL_TASK_INDEX.map((entry) => [entry.id, entry]));
const entriesBySkill = new Map<string, SkillTaskEntry[]>();
for (const entry of SKILL_TASK_INDEX) {
  entriesBySkill.set(entry.skill, [...(entriesBySkill.get(entry.skill) ?? []), entry]);
}

/** Tasks of a skill in route order: by step, then by the order inside the step. */
export const getSkillTasks = (skillId: string): readonly SkillTaskEntry[] =>
  entriesBySkill.get(skillId) ?? [];

export const getSkillById = (skillId: string): SkillDefinition | undefined =>
  skillById.get(skillId);

export const getSkillTaskEntry = (taskId: string | number): SkillTaskEntry | undefined =>
  entryByTaskId.get(String(taskId));

export const getSectionSkills = (section: SectionType): SkillDefinition[] =>
  SKILLS.filter((skill) => skill.section === section);
