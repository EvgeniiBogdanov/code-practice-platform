import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import ts from "typescript";
import prettier from "prettier";

// Keep the browser's JSX/SVG vocabulary in sync with the installed React types
// without shipping the TypeScript compiler or declaration source to the UI.
const require = createRequire(import.meta.url);
const reactRoot = dirname(require.resolve("@types/react/package.json"));
const source = ts.createSourceFile(
  "react.d.ts",
  readFileSync(resolve(reactRoot, "index.d.ts"), "utf8"),
  ts.ScriptTarget.Latest,
  true
);
const names = [];
const visit = (node) => {
  if (ts.isInterfaceDeclaration(node) && node.name.text === "IntrinsicElements") {
    for (const member of node.members) {
      if (member.name && (ts.isIdentifier(member.name) || ts.isStringLiteral(member.name)))
        names.push(member.name.text);
    }
  }
  ts.forEachChild(node, visit);
};
visit(source);
if (!names.length) throw new Error("React IntrinsicElements was not found");
const output = `// Generated by npm run generate:editor-tags from @types/react.\nimport type { JSX } from "react";\n\nexport const REACT_INTRINSIC_TAG_NAMES = ${JSON.stringify([...new Set(names)])} as const satisfies readonly (keyof JSX.IntrinsicElements)[];\n`;
writeFileSync(
  new URL("../src/shared/lib/code-editor/languages/react-intrinsic-tags.ts", import.meta.url),
  await prettier.format(output, { parser: "typescript", printWidth: 95 })
);
